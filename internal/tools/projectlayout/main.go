//go:build tools

// Command projectlayout refreshes repository files that consume the Go path definitions.
package main

import (
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/conn-castle/agent-layer/internal/projectpaths"
)

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "check the generated files without writing")
	flag.Parse()
	if err := generate(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(root string, check bool) error {
	var env strings.Builder
	var ignores strings.Builder
	portablePath := regexp.MustCompile(`^[A-Za-z0-9._/-]+$`)
	env.WriteString("# Generated by go generate ./internal/projectpaths.\n")
	for _, entry := range []struct{ key, value string }{
		{"AL_PROJECT_WORKING", projectpaths.Working},
		{"AL_PROJECT_CACHE", projectpaths.Cache},
		{"AL_PROJECT_WORKTREES", projectpaths.Worktrees},
		{"AL_PROJECT_RUNS", projectpaths.Runs},
	} {
		relative, ok := strings.CutPrefix(entry.value, ".agent-layer/")
		if !ok || relative == "." || !fs.ValidPath(relative) || !portablePath.MatchString(relative) {
			return fmt.Errorf("project directory %q must be a portable path under .agent-layer", entry.value)
		}
		fmt.Fprintf(&env, "%s=%s\n", entry.key, entry.value)
		fmt.Fprintf(&ignores, "/%s/\n", relative)
	}
	if err := syncFile(filepath.Join(root, "internal/projectpaths/layout.env"), env.String(), check); err != nil {
		return err
	}

	sections := []struct{ file, start, end, content string }{
		{"internal/templates/agent-layer.gitignore", "# BEGIN GENERATED PATHS", "# END GENERATED PATHS", ignores.String()},
		{"internal/benchmark/assets/pier_agent_layer.py", "# BEGIN GENERATED PATHS", "# END GENERATED PATHS", fmt.Sprintf(
			"REMOTE_WORKING = f\"{REMOTE_WORKSPACE}/%s\"\nREMOTE_RUN_DIRS = f\"{REMOTE_WORKSPACE}/%s {REMOTE_WORKSPACE}/%s\"\n",
			projectpaths.Working, projectpaths.Runs, projectpaths.LegacyRuns)},
		{"site/docs/reference.mdx", "{/* BEGIN GENERATED PATHS */}", "{/* END GENERATED PATHS */}", fmt.Sprintf(
			"\n| Directory | Use |\n| --- | --- |\n| `%s/` | Plans, reports, handoffs, and evidence worth retaining |\n| `%s/` | Regenerable downloads, build outputs, and disposable intermediate files |\n| `%s/` | Task worktrees created with Git and import-conflict workspaces |\n| `%s/` | Machine-managed launch and dispatch records |\n\n",
			projectpaths.Working, projectpaths.Cache, projectpaths.Worktrees, projectpaths.Runs)},
		{".agent-layer/instructions/04_conventions.md", "<!-- BEGIN GENERATED PATHS -->", "<!-- END GENERATED PATHS -->", fmt.Sprintf(
			"\n- Keep agent plans, reports, handoffs, and retained evidence under `%s/`.\n- Put regenerable downloads, build outputs, and disposable intermediate files under `%s/`.\n- Create task worktrees under `%s/` and use Git to manage them. Native harness-managed worktrees follow the harness's configured location.\n\n",
			projectpaths.Working, projectpaths.Cache, projectpaths.Worktrees)},
	}
	for _, section := range sections {
		file := filepath.Join(root, section.file)
		data, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		before, rest, foundStart := strings.Cut(string(data), section.start+"\n")
		_, after, foundEnd := strings.Cut(rest, section.end)
		if !foundStart || !foundEnd {
			return fmt.Errorf("generated path markers are missing in %s", file)
		}
		content := before + section.start + "\n" + section.content + section.end + after
		if err := syncFile(file, content, check); err != nil {
			return err
		}
	}
	return nil
}

func syncFile(file, content string, check bool) error {
	data, err := os.ReadFile(file)
	if err == nil && string(data) == content {
		return nil
	}
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if check {
		return fmt.Errorf("%s is stale. Run go generate ./internal/projectpaths", file)
	}
	return os.WriteFile(file, []byte(content), 0o644)
}

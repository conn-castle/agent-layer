package musepolicy

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

// Receipt authorizes bounded cleanup of a workspace's native policy rules.
// It contains no credentials. Keep this format compatible with existing syncs.
type Receipt struct {
	GeneratedBy string `json:"generated_by"`
	Directory   string `json:"directory"`
	Root        string `json:"workspace_root"`
}

// ParseReceipt validates the shared Agent Layer ownership receipt format.
func ParseReceipt(data []byte) (*Receipt, error) {
	var receipt Receipt
	if err := json.Unmarshal(data, &receipt); err != nil {
		return nil, err
	}
	if receipt.GeneratedBy != "agent-layer" || !filepath.IsAbs(receipt.Directory) || !filepath.IsAbs(receipt.Root) || filepath.Base(receipt.Directory) != "muse" {
		return nil, fmt.Errorf("expected generated_by agent-layer, absolute directory and workspace_root, and a native directory named muse")
	}
	return &receipt, nil
}

// IsOrphan reports only provable loss of ownership in this native directory.
// Unreadable, malformed, symlinked and unexpected filesystem state is uncertain
// and must be kept. Sync calls this while holding approval-policy.lock; doctor
// uses the same predicate read-only and may observe a concurrent transition.
func IsOrphan(directory, root string) bool {
	return ownershipState(directory, root) == ownershipOrphan
}

type ownership int

const (
	ownershipUnknown ownership = iota
	ownershipValid
	ownershipOrphan
)

func ownershipState(directory, root string) ownership {
	info, err := os.Lstat(root)
	if os.IsNotExist(err) {
		return ownershipOrphan
	}
	if err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return ownershipUnknown
	}
	local := filepath.Join(root, ".muse")
	info, err = os.Lstat(local)
	if os.IsNotExist(err) {
		return ownershipOrphan
	}
	if err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return ownershipUnknown
	}
	data, err := readRegular(filepath.Join(local, "agent-layer-policy.json"))
	if err != nil {
		return ownershipUnknown
	}
	if data == nil {
		return ownershipOrphan
	}
	receipt, err := ParseReceipt(data)
	if err != nil {
		return ownershipUnknown
	}
	// Receipts generated by sync contain clean paths. Cleaning unexpected
	// spellings here could change identity across symlink/.. components.
	if filepath.Clean(receipt.Root) != receipt.Root || filepath.Clean(receipt.Directory) != receipt.Directory {
		return ownershipUnknown
	}
	if state := directoryOwnership(root, receipt.Root); state != ownershipValid {
		return state
	}
	return directoryOwnership(directory, receipt.Directory)
}

// Native config paths can differ through HOME or XDG symlink aliases. Path
// spelling alone cannot prove that a receipt names a different policy store.
func directoryOwnership(directory, recorded string) ownership {
	same, err := SameDirectory(directory, recorded)
	if err != nil {
		return ownershipUnknown
	}
	if same {
		return ownershipValid
	}
	return ownershipOrphan
}

// SameDirectory compares path spellings by filesystem identity, following
// symlinks. A missing recorded path proves a different directory; other stat
// errors are uncertain and callers must preserve the recorded grants.
func SameDirectory(directory, recorded string) (bool, error) {
	if directory == recorded {
		return true, nil
	}
	recordedInfo, err := os.Stat(recorded)
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	currentInfo, err := os.Stat(directory)
	if err != nil {
		return false, err
	}
	return os.SameFile(recordedInfo, currentInfo), nil
}
